/** Room-level tests for the v0.7 tables. They need a device or emulator: `./gradlew connectedDebugAndroidTest`. */
@RunWith(AndroidJUnit4::class)
class V07DatabaseTest {
    private val ctx: Context = ApplicationProvider.getApplicationContext()
    private val file = "v07-test.db"
    @Before fun clean() { ctx.deleteDatabase(file) }
    @After fun after() { ctx.deleteDatabase(file) }

    private fun open() = Room.databaseBuilder(ctx, AppDatabase::class.java, file).addMigrations(AppMigrations.MIGRATION_1_2).build()

    private fun media(id: String, fp: String?, tags: String = "") =
        MediaItemEntity(id, "VIDEO", "$id.mp4", "video/mp4", "/x/$id", 10, 1000, 1080, 1920, 0, 1, fp, null, tags)

    @Test fun draftsMediaBrandsAndUsageSurviveClosingAndReopeningTheDatabase() = runBlocking {
        var db = open()
        db.drafts().upsert(ComposerDraftEntity("d1", "Trip", "caption", JsonLists.encodeMap(mapOf(Platform.TIKTOK to "tt only")), "#a", JsonLists.encode(listOf("m1")), JsonLists.encode(listOf("a1")), null, "funny", "hi", 5000L, "Asia/Kolkata", 1, 2))
        db.media().upsertAll(listOf(media("m1", "fp1", "goa,beach")))
        db.brands().upsert(BrandProfile("b1", "Chai Co", "d", "marketing", "a", "#tea", "en", "cta", "sig", 1, 1, true, false))
        db.aiUsage().upsert(AiUsageEntity(1, "free", 5000, 270, 0, 4730, "2026-11-01", "2026-12-01T00:00:00.000Z", 6, 99))
        db.close()

        db = open()
        val d = db.drafts().get("d1")!!
        assertEquals("caption", d.baseCaption); assertEquals(mapOf(Platform.TIKTOK to "tt only"), d.captionMap); assertEquals(listOf("m1"), d.mediaIdList)
        assertEquals("Asia/Kolkata", d.zoneId); assertEquals(5000L, d.plannedAt)
        assertEquals(listOf("goa", "beach"), db.media().all().single().tagList)
        assertTrue(db.brands().dirty().single().dirty)
        assertEquals(4730L, db.aiUsage().get()!!.remaining)
        db.close()
    }

    @Test fun mediaQueriesAndFolders() = runBlocking {
        val db = open()
        db.media().upsertAll(listOf(media("a", "same"), media("b", "other"), media("c", "same")))
        assertEquals("same", db.media().byFingerprint("same")!!.fingerprint)
        db.mediaFolders().upsert(MediaFolderEntity("f", "Holiday", 1))
        db.media().setFolder(listOf("a", "b"), "f")
        assertEquals(2, db.media().all().count { it.folderId == "f" })
        db.media().clearFolder("f"); db.mediaFolders().delete("f")
        assertTrue(db.media().all().all { it.folderId == null })
        assertEquals(30L, db.media().totalBytes())
        db.media().setTags("a", "x,y"); assertEquals(listOf("x", "y"), db.media().byIds(listOf("a")).single().tagList)
        db.media().delete(listOf("a")); assertEquals(2, db.media().observe().first().size)
        db.close()
    }

    @Test fun deletedBrandsAreHiddenFromTheList() = runBlocking {
        val db = open()
        db.brands().upsert(BrandProfile("b1", "A", "", "casual", "", "", "en", "", "", 1, 1, true, true))
        db.brands().upsert(BrandProfile("b2", "B", "", "casual", "", "", "en", "", "", 1, 1, true, false))
        assertEquals(listOf("B"), db.brands().observe().first().map { it.name })
        db.close()
    }

    @Test fun draftsAreNewestFirst() = runBlocking {
        val db = open()
        db.drafts().upsert(ComposerDraftEntity("old", "", "", "{}", "", "[]", "[]", null, "casual", "en", 0, "", 1, 1))
        db.drafts().upsert(ComposerDraftEntity("new", "", "", "{}", "", "[]", "[]", null, "casual", "en", 0, "", 1, 9))
        assertEquals(listOf("new", "old"), db.drafts().observe().first().map { it.id }); assertEquals(2, db.drafts().count())
        db.close()
    }
}

/**
 * Proves 1 -> 2 keeps v0.6 data. Requires app/schemas/com.example.autoposter.AppDatabase/1.json (build the v0.6 tag once and commit
 * the file) and 2.json (generated by building v0.7). Without them this test fails with "Cannot find the schema file" — see PROJECT_STATUS.md.
 */
@RunWith(AndroidJUnit4::class)
class AppMigrationTest {
    @get:Rule val helper = MigrationTestHelper(InstrumentationRegistry.getInstrumentation(), AppDatabase::class.java, emptyList(), FrameworkSQLiteOpenHelperFactory())

    @Test fun migrate1To2KeepsPostsAndAddsTables() {
        helper.createDatabase("migration-test", 1).use { db ->
            db.execSQL("INSERT INTO posts (id, campaignId, accountId, accountLabel, platform, filePath, name, fingerprint, text, scheduledAt, status, progress, attempts, remoteId, error, createdAt, finishedAt, sizeBytes, views, likes, comments) VALUES ('p1','c','a','Main','YOUTUBE','/f','n',NULL,'t',1,'QUEUED',0,0,NULL,NULL,1,0,0,-1,-1,-1)")
        }
        helper.runMigrationsAndValidate("migration-test", 2, true, AppMigrations.MIGRATION_1_2).use { db ->
            db.query("SELECT COUNT(*) FROM posts").use { c -> c.moveToFirst(); assertEquals(1, c.getInt(0)) }
            for (t in listOf("brand_profiles", "media_items", "media_folders", "composer_drafts", "ai_usage_cache")) db.query("SELECT COUNT(*) FROM $t").use { c -> assertTrue(c.moveToFirst()) }
        }
    }
}
